#!/usr/bin/env node
import { existsSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { registerHooks } from "node:module";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

registerHooks({
  resolve(specifier, context, nextResolve) {
    if (
      specifier.startsWith(".") &&
      specifier.endsWith(".js") &&
      context.parentURL?.endsWith(".ts")
    ) {
      const sibling = new URL(specifier.replace(/\.js$/, ".ts"), context.parentURL);
      if (existsSync(sibling)) return nextResolve(sibling.href, context);
    }
    return nextResolve(specifier, context);
  },
});
const { OFFERED_TEMPLATES } = await import("../packages/core/src/new.ts");

if (process.argv.includes("--list")) {
  process.stdout.write(`${OFFERED_TEMPLATES.join("\n")}\n`);
  process.exit(0);
}

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const BENCH = join(ROOT, "bench");
const TEMPLATES = join(ROOT, "templates");

const files = {};
const walk = (dir, base) => {
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const path = join(dir, entry.name);
    const key = base === "" ? entry.name : `${base}/${entry.name}`;
    if (entry.isDirectory()) walk(path, key);
    else if ([".md", ".json", ".yml"].some((extension) => entry.name.endsWith(extension))) {
      files[key] = readFileSync(path, "utf8");
    }
  }
};
walk(BENCH, "");

const out = `// GENERATED by scripts/embed-bench.mjs. Do not edit.
//
// The bench, carried inside the CLI so that \`mktrue check\` and \`mktrue sync\`
// work in a repository that has no bench of its own — which is every repository
// the kit manages.

export const EMBEDDED_BENCH: Readonly<Record<string, string>> = ${JSON.stringify(files, null, 2)};
`;
writeFileSync(join(ROOT, "packages/cli/src/bench.embedded.ts"), out);
console.log(`embedded ${Object.keys(files).length} bench files`);

const embedded = new Set();
for (const name of OFFERED_TEMPLATES) {
  embedded.add(name);
  const manifest = JSON.parse(readFileSync(join(TEMPLATES, name, "template.json"), "utf8"));
  for (const base of manifest.composes ?? []) embedded.add(base);
}

const templateFiles = {};
const walkTemplate = (dir, base) => {
  for (const entry of readdirSync(dir, { withFileTypes: true }).sort((a, b) =>
    a.name.localeCompare(b.name),
  )) {
    const rel = `${base}/${entry.name}`;
    if (entry.isDirectory()) walkTemplate(join(dir, entry.name), rel);
    else templateFiles[rel] = readFileSync(join(dir, entry.name), "utf8");
  }
};
for (const name of [...embedded].sort()) walkTemplate(join(TEMPLATES, name), name);

const templatesOut = `// GENERATED by scripts/embed-bench.mjs. Do not edit.
//
// The templates \`mktrue new\` offers, and the templates they compose, carried
// inside the CLI so that \`new\` works where there is no kit checkout.

export const EMBEDDED_TEMPLATES: Readonly<Record<string, string>> = ${JSON.stringify(templateFiles, null, 2)};
`;
writeFileSync(join(ROOT, "packages/cli/src/templates.embedded.ts"), templatesOut);
console.log(`embedded ${Object.keys(templateFiles).length} template files`);
